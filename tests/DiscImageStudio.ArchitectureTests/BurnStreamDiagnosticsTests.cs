using System.IO;
using DiscImageStudio.Burning;

internal static class BurnStreamDiagnosticsTests
{
    internal static void Run()
    {
        TestSnapshotDoesNotReadOrAdvanceSeek();
        TestPartialGenerationAndWaitingReader();
        TestBackpressureRemainsBounded();
        TestFailureAndCancellationRemainObservable();
        Console.WriteLine("burn-stream-diagnostics: passed (non-consuming snapshots, seek/read separation, backpressure, producer failures and cancellation; no device access)");
    }

    private static void TestSnapshotDoesNotReadOrAdvanceSeek()
    {
        byte[] expected = Enumerable.Range(0, 64).Select(value => (byte)value).ToArray();
        using GeneratedContentComStream stream = new(expected.Length,
            (output, _) => output.Write(expected), null, CancellationToken.None);
        stream.WaitUntilPrebuffered(CancellationToken.None);
        WaitFor(() => stream.GetDiagnosticSnapshot().ProducerState == "Completed", "producer completes");
        GeneratedContentDiagnosticSnapshot before = stream.GetDiagnosticSnapshot();
        Require(before.GeneratedBytes == expected.Length && before.PublishedBytes == expected.Length,
            "all generated bytes and published bytes are visible");
        Require(before.ReadBytes == 0 && before.BufferedBytes == expected.Length && before.PrebufferReady,
            "prebuffering and snapshots do not consume data");
        Require(before.PrebufferThresholdBytes == expected.Length
            && before.QueueCapacityBytes == OpticalBurnBufferOptions.Default.CapacityBytes,
            "small streams report the effective prebuffer threshold and configured queue capacity");

        stream.Seek(0, 2, IntPtr.Zero);
        Require(stream.GetDiagnosticSnapshot().ReadBytes == 0,
            "the metadata seek to the stream end is not recorded as a read");
        stream.Seek(0, 0, IntPtr.Zero);
        for (int index = 0; index < 8; index++) _ = stream.GetDiagnosticSummary();
        byte[] first = new byte[13];
        stream.Read(first, first.Length, IntPtr.Zero);
        GeneratedContentDiagnosticSnapshot partial = stream.GetDiagnosticSnapshot();
        Require(first.SequenceEqual(expected.Take(first.Length)) && partial.ReadBytes == first.Length
            && partial.BufferedBytes == expected.Length - first.Length,
            "reading after repeated snapshots returns the original prefix and updates only consumption");
        byte[] rest = new byte[expected.Length - first.Length];
        stream.Read(rest, rest.Length, IntPtr.Zero);
        Require(rest.SequenceEqual(expected.Skip(first.Length)), "the remaining bytes are intact");
        GeneratedContentDiagnosticSnapshot after = stream.GetDiagnosticSnapshot();
        Require(after.ReadBytes == expected.Length && after.BufferedBytes == 0,
            "the drained stream reports no published bytes remaining");
        string summary = stream.GetDiagnosticSummary();
        Require(summary.Contains("不代表盘片写入量", StringComparison.Ordinal),
            "source consumption is explicitly distinguished from physical writes");
    }

    private static void TestPartialGenerationAndWaitingReader()
    {
        using ManualResetEventSlim partialReady = new();
        using ManualResetEventSlim releaseProducer = new();
        using GeneratedContentComStream stream = new(4, (output, token) =>
        {
            output.WriteByte(11);
            output.WriteByte(13);
            partialReady.Set();
            releaseProducer.Wait(token);
            output.Write(new byte[] { 17, 19 });
        }, null, CancellationToken.None);
        Require(partialReady.Wait(TimeSpan.FromSeconds(5)), "partial producer starts");
        GeneratedContentDiagnosticSnapshot pending = stream.GetDiagnosticSnapshot();
        Require(pending.GeneratedBytes == 2 && pending.PublishedBytes == 0 && pending.BufferedBytes == 0
            && pending.ProducerState == "Running" && !pending.PrebufferReady,
            "unpublished partial bytes are generated but not available to the reader");
        byte[] result = new byte[4];
        Task reader = Task.Run(() => stream.Read(result, result.Length, IntPtr.Zero));
        try
        {
            WaitFor(() => stream.GetDiagnosticSnapshot().ReaderWaitingForData,
                "waiting for generation is observable without blocking the snapshot");
            Require(stream.GetDiagnosticSnapshot().ReaderWaitCount == 1,
                "a stalled reader reports one data wait");
        }
        finally { releaseProducer.Set(); }
        Require(reader.Wait(TimeSpan.FromSeconds(5)), "the reader completes after generation resumes");
        Require(result.SequenceEqual(new byte[] { 11, 13, 17, 19 })
            && !stream.GetDiagnosticSnapshot().ReaderWaitingForData,
            "the resumed reader preserves bytes and clears its waiting flag");
    }

    private static void TestBackpressureRemainsBounded()
    {
        int chunk = GeneratedContentComStream.ChunkBytes;
        OpticalBurnBufferOptions options = new(chunk, chunk);
        using GeneratedContentComStream stream = new(chunk * 3L,
            (output, _) => output.Write(new byte[chunk * 3]), null, CancellationToken.None, options);
        stream.WaitUntilPrebuffered(CancellationToken.None);
        WaitFor(() => stream.GetDiagnosticSnapshot().ProducerWaitingForBuffer, "the full queue stops the producer");
        for (int index = 0; index < 16; index++) _ = stream.GetDiagnosticSummary();
        GeneratedContentDiagnosticSnapshot full = stream.GetDiagnosticSnapshot();
        Require(full.PublishedBytes == chunk && full.ReadBytes == 0 && full.BufferedBytes == chunk,
            "diagnostic sampling never drains the full queue or admits another chunk");
        Require(full.GeneratedBytes == chunk * 2L && full.ProducerWaitingForBuffer,
            "the blocked unpublished chunk is distinguished from queued bytes");
        byte[] bytes = new byte[chunk * 3];
        stream.Read(bytes, bytes.Length, IntPtr.Zero);
        WaitFor(() => stream.GetDiagnosticSnapshot().ProducerState == "Completed", "producer finishes after draining");
        GeneratedContentDiagnosticSnapshot drained = stream.GetDiagnosticSnapshot();
        Require(drained.PublishedBytes == bytes.Length && drained.ReadBytes == bytes.Length
            && drained.BufferedBytes == 0 && !drained.ProducerWaitingForBuffer,
            "backpressure and byte totals recover after the consumer drains the queue");
    }

    private static void TestFailureAndCancellationRemainObservable()
    {
        IOException expected = new("private-input-path-must-not-appear-in-summary");
        using (GeneratedContentComStream failed = new(10, (_, _) => throw expected, null, CancellationToken.None))
        {
            Exception? observed = null;
            try { failed.WaitUntilPrebuffered(CancellationToken.None); }
            catch (IOException exception) { observed = exception; }
            Require(ReferenceEquals(observed, expected), "prebuffer failure retains the original exception");
            GeneratedContentDiagnosticSnapshot snapshot = failed.GetDiagnosticSnapshot();
            Require(snapshot.ProducerState == "Failed" && snapshot.ProducerExceptionType == typeof(IOException).FullName
                && snapshot.ProducerHResult == expected.HResult,
                "failed generation is visible with its exception type and HRESULT");
            Require(!failed.GetDiagnosticSummary().Contains(expected.Message, StringComparison.Ordinal),
                "the compact diagnostic summary does not expose generator messages or paths");
        }

        using CancellationTokenSource cancellation = new();
        using ManualResetEventSlim entered = new();
        using GeneratedContentComStream cancelled = new(10, (_, token) =>
        {
            entered.Set();
            token.WaitHandle.WaitOne();
            token.ThrowIfCancellationRequested();
        }, null, cancellation.Token);
        Require(entered.Wait(TimeSpan.FromSeconds(5)), "the cancellation producer starts");
        cancellation.Cancel();
        WaitFor(() => cancelled.GetDiagnosticSnapshot().ProducerState == "Cancelled", "producer cancellation is observed");
        GeneratedContentDiagnosticSnapshot cancelledSnapshot = cancelled.GetDiagnosticSnapshot();
        Require(cancelledSnapshot.CancellationRequested && cancelledSnapshot.ReadBytes == 0,
            "cancellation state is captured without consuming data");
        bool threw = false;
        try { cancelled.WaitUntilPrebuffered(CancellationToken.None); }
        catch (OperationCanceledException) { threw = true; }
        Require(threw, "diagnostics preserve cancellation propagation");
    }

    private static void WaitFor(Func<bool> condition, string message)
        => Require(SpinWait.SpinUntil(condition, TimeSpan.FromSeconds(5)), message);

    private static void Require(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException("Burn stream diagnostics: " + message);
    }
}
